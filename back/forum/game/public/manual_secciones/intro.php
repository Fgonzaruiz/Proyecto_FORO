<p>Bienvenido al Manual Oficial del RPG de Foro One Piece. Este documento recoge todas las reglas, sistemas, historias y mec&aacute;nicas que rigen el mundo del juego.</p>
<p>El foro de rol est&aacute; ambientado en el universo de <strong>One Piece</strong>, creado por Eiichiro Oda. Los jugadores podr&aacute;n crear su propio personaje, navegar por los mares, formar tripulaciones, enfrentarse a enemigos y descubrir los secretos del mundo.</p>

<h3>1.1 &iquest;Qu&eacute; es el RPG?</h3>
<p>Es un juego de rol por turnos donde cada jugador controla un personaje &uacute;nico. Las acciones se resuelven mediante dados, estad&iacute;sticas y la interpretaci&oacute;n del jugador.</p>
<blockquote>"El &eacute;xito no se mide por las batallas ganadas, sino por las historias que creamos juntos."</blockquote>

