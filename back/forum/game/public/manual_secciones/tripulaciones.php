<h3>6.3 Alianzas</h3>
<p>Las tripulaciones pueden formar alianzas temporales o permanentes. Una alianza permite compartir recursos, informaci&oacute;n y rutas. Sin embargo, las alianzas grandes atraen la atenci&oacute;n de la Marina.</p>
