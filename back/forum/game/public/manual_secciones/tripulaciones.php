<p>Formar o unirse a una tripulaci&oacute;n es esencial para sobrevivir en el Grand Line.</p>

<h3>6.1 Crear una Tripulaci&oacute;n</h3>
<p>Para fundar una tripulaci&oacute;n se necesita:</p>
<ul>
  <li>Un m&iacute;nimo de <strong>3 miembros</strong></li>
  <li>Un <strong>barco</strong> (adquirible en astilleros)</li>
  <li>Una <strong>bandera Jolly Roger</strong> &uacute;nica</li>
  <li>Registro en el <strong>Gobierno Mundial</strong> o declaraci&oacute;n de independencia</li>
</ul>

