<h3>8.2 Eventos del Mundo</h3>
<p>El mundo est&aacute; vivo. Peri&oacute;dicamente ocurren eventos globales que afectan a todos los jugadores:</p>
<ul>
  <li><strong>Guerra Mundial:</strong> Conflicto entre bandos masivos.</li>
  <li><strong>Subasta de Frutas:</strong> Aparece una fruta rara en el mercado negro.</li>
  <li><strong>Tormenta del Grand Line:</strong> Clima extremo en todas las rutas.</li>
  <li><strong>Festival del Mar:</strong> D&iacute;a de bonificaciones y misiones especiales.</li>
  <li><strong>Buster Call:</strong> La Marina arrasa una isla. &iexcl;Huye o enfr&eacute;ntalos!</li>
</ul>

<h3>8.3 Sistema de Experiencia</h3>
<p>Los personajes suben de nivel al acumular experiencia (EXP). Cada nivel otorga <strong>5 puntos</strong> para distribuir en stats. El EXP se obtiene mediante misiones, combates y participaci&oacute;n en eventos.</p>
<div class="rpg-manual-formula">
  <code>EXP necesaria = Nivel actual &times; 100 + 50</code>
</div>
