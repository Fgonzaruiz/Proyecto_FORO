<p>El combate se resuelve mediante un sistema h&iacute;brido de dados y estad&iacute;sticas.</p>

<h3>3.1 Iniciativa y Turnos</h3>
<p>Al inicio del combate, cada participante lanza 1d20 + su stat de <strong>DP (Destreza)</strong>. El orden descendente determina los turnos.</p>

<h3>3.2 Ataques</h3>
<p>Un ataque b&aacute;sico se resuelve as&iacute;:</p>
<div class="rpg-manual-formula">
  <code>Da&ntilde;o = (FP del atacante &times; 0.5) + (1d20) &minus; (RP del defensor &times; 0.3)</code>
</div>

