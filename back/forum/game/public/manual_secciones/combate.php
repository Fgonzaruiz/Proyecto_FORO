<h3>3.4 Da&ntilde;o Cr&iacute;tico</h3>
<p>Si en el dado de ataque obtienes un 20 natural (cr&iacute;tico), el da&ntilde;o se duplica. Si obtienes un 1 natural (pifia), el ataque falla autom&aacute;ticamente y el personaje queda expuesto.</p>
