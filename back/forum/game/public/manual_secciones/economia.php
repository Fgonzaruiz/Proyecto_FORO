<h3>7.3 Tiendas y Objetos</h3>
<p>Los objetos se clasifican por rareza:</p>
<ul>
  <li><strong>Com&uacute;n:</strong> Objetos b&aacute;sicos, se encuentran en cualquier tienda.</li>
  <li><strong>Poco Com&uacute;n:</strong> Equipo de calidad, tiendas especializadas.</li>
  <li><strong>Raro:</strong> Armas y objetos &uacute;nicos, forjados por maestros.</li>
  <li><strong>&Eacute;pico:</strong> Reliquias hist&oacute;ricas, se obtienen en mazmorras.</li>
  <li><strong>Legendario:</strong> Objetos &uacute;nicos en el mundo, como las Saijo O Wazamono.</li>
</ul>
