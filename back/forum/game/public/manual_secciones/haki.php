<p>El Haki es una fuerza espiritual latente en todo ser vivo. Se divide en tres tipos principales.</p>

<h3>5.1 Haki de Armadura (Busoshoku)</h3>
<p>Endurece el cuerpo como armadura invisible. Requiere: <strong>HP &ge; 30, VP &ge; 50</strong></p>
<ul>
  <li><strong>Nivel 1:</strong> Cubre extremidades (+10 def, +10 atq)</li>
  <li><strong>Nivel 2:</strong> Cubre todo el cuerpo (+25 def, +15 atq)</li>
  <li><strong>Nivel 3:</strong> Emisi&oacute;n (Ryuo). Golpea sin contacto (+40 def, +30 atq)</li>
  <li><strong>Nivel 4:</strong> Penetraci&oacute;n interna (+50 def, ignora defensa externa)</li>
</ul>

<h3>5.2 Haki de Observaci&oacute;n (Kenbunshoku)</h3>
<p>Permite sentir la presencia y emociones de otros. Requiere: <strong>IP &ge; 40, VP &ge; 60</strong></p>
<ul>
  <li><strong>Nivel 1:</strong> Detecta presencias en 50m</li>
  <li><strong>Nivel 2:</strong> Predice movimientos b&aacute;sicos (+15 evasi&oacute;n)</li>
  <li><strong>Nivel 3:</strong> Predicci&oacute;n avanzada (+30 evasi&oacute;n, ve intenciones)</li>
  <li><strong>Nivel 4:</strong> Visi&oacute;n del futuro (+50 evasi&oacute;n, anticipa ataques)</li>
</ul>

<h3>5.3 Haki del Rey (Haoshoku)</h3>
<p>Imbuye la voluntad del usuario en su entorno. Es innato, no se entrena f&aacute;cilmente.</p>
<ul>
  <li><strong>Nivel 1:</strong> Desmaya a d&eacute;biles de voluntad en &aacute;rea</li>
  <li><strong>Nivel 2:</strong> Desmaya a enemigos de nivel bajo-medio</li>
  <li><strong>Nivel 3:</strong> Recubrimiento de Haoshoku sobre ataques (&times;3 da&ntilde;o)</li>
</ul>
<p>Requiere: <strong>VP &ge; 100</strong> para manifestarse.</p>
