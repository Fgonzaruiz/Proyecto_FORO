<h3>4.2 Despertar</h3>
<p>Una fruta puede "despertarse" cuando el usuario domina completamente su poder. El despertar permite:</p>
<ul>
  <li><strong>Paramecia:</strong> Extender el poder al entorno.</li>
  <li><strong>Zoan:</strong> Transformaci&oacute;n adicional m&aacute;s poderosa.</li>
  <li><strong>Logia:</strong> Control elemental masivo y cambio clim&aacute;tico local.</li>
</ul>
<p>El despertar requiere un stat de <strong>IP (Intelecto) &ge; 100</strong> y una misi&oacute;n especial de desarrollo.</p>

<h3>4.3 Debilidades</h3>
<ul>
  <li>El usuario <strong>no puede nadar</strong>. Pierde toda fuerza al sumergirse.</li>
  <li>El <strong>Kairoseki</strong> anula los poderes de la fruta.</li>
  <li>El <strong>Haki de Armadura</strong> puede golpear cuerpos de Logia.</li>
  <li>El contacto con <strong>agua del mar</strong> drena la energ&iacute;a del usuario.</li>
</ul>
