<h3>9.1 Normas de Conducta</h3>
<ul>
  <li>Est&aacute; prohibido el <strong>metagaming</strong> (usar informaci&oacute;n fuera del personaje).</li>
  <li>El <strong>powergaming</strong> (controlar las acciones de otros) no est&aacute; permitido.</li>
  <li>El <strong>godmoding</strong> (ser invencible) conlleva sanciones.</li>
  <li>Respeta las decisiones del <strong>staff</strong> y los dados.</li>
  <li>El <strong>combate PvP</strong> requiere consentimiento de ambas partes.</li>
</ul>

