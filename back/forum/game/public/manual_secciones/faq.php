<div class="rpg-manual-faq">
  <div class="rpg-manual-faq-item">
    <h3>&iquest;C&oacute;mo empiezo a jugar?</h3>
    <p>Crea un personaje en la secci&oacute;n <strong>Personaje</strong>, distribuye tus stats y publica tu ficha en el foro de presentaciones. Un miembro del staff te dar&aacute; la bienvenida.</p>
  </div>
  <div class="rpg-manual-faq-item">
    <h3>&iquest;Puedo cambiar mi fruta del diablo?</h3>
    <p>No, las frutas son permanentes. Sin embargo, existen eventos extremadamente raros donde podr&iacute;as obtener una segunda fruta (riesgo de muerte).</p>
  </div>
  <div class="rpg-manual-faq-item">
    <h3>&iquest;C&oacute;mo consigo un barco?</h3>
    <p>Los barcos se compran en astilleros, se roban a otros piratas, se construyen con materiales o se obtienen como recompensa de misiones.</p>
  </div>
  <div class="rpg-manual-faq-item">
    <h3>&iquest;El Haki del Rey se puede entrenar?</h3>
    <p>No directamente. El Haoshoku es innato. Solo se manifiesta en personas con un esp&iacute;ritu de l&iacute;der nato. Si tu personaje no lo tiene, no podr&aacute; obtenerlo.</p>
  </div>
  <div class="rpg-manual-faq-item">
    <h3>&iquest;Puedo morir permanentemente?</h3>
    <p>S&iacute;, la muerte es permanente en este foro. Sin embargo, es rara y solo ocurre en circunstancias extremas o con consentimiento del jugador.</p>
  </div>
  <div class="rpg-manual-faq-item">
    <h3>&iquest;C&oacute;mo funcionan las alianzas?</h3>
    <p>Dos o m&aacute;s tripulaciones pueden declarar una alianza. Debe ser registrada en el foro de Alianzas y aprobada por un administrador.</p>
  </div>
  <div class="rpg-manual-faq-item">
    <h3>&iquest;Hay l&iacute;mite de personajes?</h3>
    <p>Cada usuario puede tener hasta <strong>3 personajes</strong> activos simult&aacute;neamente.</p>
  </div>
  <div class="rpg-manual-faq-item">
    <h3>&iquest;Qu&eacute; pasa si no posteo en 2 semanas?</h3>
    <p>Tu personaje ser&aacute; marcado como <strong>inactivo</strong>. Si pasan 3 meses sin actividad, el personaje se archiva.</p>
  </div>
